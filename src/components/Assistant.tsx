import { useEffect, useRef, useState, type FormEvent } from 'react';
import { ASSISTANT_URL, AssistantError, MAX_INPUT, askAssistant, type ChatMessage } from '../lib/assistant';
import Reveal from './Reveal';
import Section from './Section';
import { SendIcon, SparkIcon } from './Icons';

const SUGGESTIONS = ['What has Vansh built?', 'Which technologies does he use?', 'Tell me about his education', 'How can I contact him?'];

export default function Assistant() {
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const logRef = useRef<HTMLDivElement>(null);
  const abortRef = useRef<AbortController | null>(null);
  const configured = Boolean(ASSISTANT_URL);

  useEffect(() => () => abortRef.current?.abort(), []);
  useEffect(() => {
    const el = logRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages, busy]);

  const send = async (text: string) => {
    const content = text.trim().slice(0, MAX_INPUT);
    if (!content || busy || !ASSISTANT_URL) return;
    const next: ChatMessage[] = [...messages, { role: 'user', content }];
    setMessages(next);
    setInput('');
    setError(null);
    setBusy(true);
    abortRef.current?.abort();
    abortRef.current = new AbortController();
    try {
      const reply = await askAssistant(ASSISTANT_URL, next, abortRef.current.signal);
      setMessages([...next, { role: 'assistant', content: reply }]);
    } catch (e) {
      if ((e as Error).name !== 'AbortError') setError(e instanceof AssistantError ? e.message : 'Something went wrong.');
    } finally {
      setBusy(false);
    }
  };

  const onSubmit = (event: FormEvent) => {
    event.preventDefault();
    void send(input);
  };

  return (
    <Section
      id="assistant"
      eyebrow="Ask"
      title="Ask about my work"
      description="An AI assistant that answers questions about my background, skills and projects. Answers are generated by a language model and may be imperfect, so check the sections above for the source of truth."
    >
      <Reveal>
        <div className="mx-auto max-w-3xl overflow-hidden rounded-xl border border-line-strong bg-surface">
          {!configured && (
            <p role="status" className="border-b border-line bg-amber/10 px-4 py-3 text-sm text-ink">
              <strong>Not connected.</strong> This development preview has no backend configured. Set <code className="font-mono">VITE_ASSISTANT_API_URL</code>{' '}
              to your deployed <code className="font-mono">api/assistant</code> endpoint (see README). This panel is hidden in production builds until you do.
            </p>
          )}
          <div ref={logRef} role="log" aria-live="polite" aria-label="Conversation" className="h-72 space-y-3 overflow-y-auto p-4 sm:p-5">
            {messages.length === 0 && (
              <div className="flex h-full flex-col items-center justify-center gap-4 text-center">
                <SparkIcon className="h-6 w-6 text-accent" />
                <p className="text-sm text-mute">Ask a question, or try one of these:</p>
                <div className="flex flex-wrap justify-center gap-2">
                  {SUGGESTIONS.map((s) => (
                    <button
                      key={s}
                      type="button"
                      disabled={!configured}
                      onClick={() => void send(s)}
                      className="rounded-full border border-line px-3 py-1.5 text-xs text-mute transition-colors hover:border-accent/50 hover:text-ink disabled:cursor-not-allowed disabled:opacity-50"
                    >
                      {s}
                    </button>
                  ))}
                </div>
              </div>
            )}
            {messages.map((m, i) => (
              <div key={i} className={m.role === 'user' ? 'flex justify-end' : 'flex justify-start'}>
                <p
                  className={`max-w-[85%] whitespace-pre-wrap rounded-2xl px-3.5 py-2 text-sm leading-relaxed ${
                    m.role === 'user' ? 'bg-accent text-on-accent' : 'border border-line bg-surface2 text-ink'
                  }`}
                >
                  {m.content}
                </p>
              </div>
            ))}
            {busy && <p className="text-xs text-faint">Thinking…</p>}
            {error && (
              <p role="alert" className="text-sm text-danger">
                {error}
              </p>
            )}
          </div>
          <form onSubmit={onSubmit} className="flex items-center gap-2 border-t border-line p-3">
            <label htmlFor="assistant-input" className="sr-only">
              Your question
            </label>
            <input
              id="assistant-input"
              value={input}
              maxLength={MAX_INPUT}
              disabled={!configured || busy}
              onChange={(e) => setInput(e.target.value)}
              placeholder={configured ? 'Ask about projects, skills, education…' : 'Assistant not connected'}
              className="min-w-0 flex-1 rounded-lg border border-line-strong bg-bg px-3 py-2 text-sm text-ink placeholder:text-faint focus:border-accent/60 focus:outline-none disabled:opacity-60"
            />
            <button
              type="submit"
              disabled={!configured || busy || input.trim() === ''}
              aria-label="Send question"
              className="rounded-lg bg-accent p-2.5 text-on-accent transition hover:bg-accent/90 disabled:cursor-not-allowed disabled:opacity-50"
            >
              <SendIcon />
            </button>
          </form>
        </div>
      </Reveal>
    </Section>
  );
}
